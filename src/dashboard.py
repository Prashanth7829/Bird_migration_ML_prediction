# ============================================================

@st.cache_data(show_spinner=False)
def load_feature_importance() -> dict[
    str,
    list[dict[str, object]],
]:
    """
    Load grouped feature importance generated during training.

    Expected structure:

    {
        "random_forest": [
            {
                "feature": "...",
                "importance": 0.123
            }
        ]
    }
    """

    path = MODELS_DIR / "feature_importance.json"

    if not path.exists():
        return {}

    try:
        return json.loads(
            path.read_text(
                encoding="utf-8"
            )
        )

    except json.JSONDecodeError:
        return {}


def get_model_feature_importance(
    model_key: str,
) -> pd.DataFrame:
    """Return feature importance for one model as a DataFrame."""

    importance = load_feature_importance()

    values = importance.get(model_key, [])

    if not values:
        return pd.DataFrame(
            columns=[
                "feature",
                "importance",
            ]
        )

    result = pd.DataFrame(values)

    if "importance" in result.columns:
        result["importance"] = pd.to_numeric(
            result["importance"],
            errors="coerce",
        )

    return result.sort_values(
        "importance",
        ascending=False,
    ).reset_index(drop=True)


