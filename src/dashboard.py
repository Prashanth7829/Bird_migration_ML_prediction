# ============================================================
# SINGLE RECORD PREDICTION
# ============================================================

def prediction_table(
    models: dict[str, object],
    frame: pd.DataFrame,
) -> pd.DataFrame:
    """
    Run one migration record through every available model.

    Returns:

    Model
    Prediction
    Success Probability
    Failure Probability
    """

    if not models:
        raise ValueError(
            "No trained models are available. "
            "Run `python -m src.train` first."
        )

    prepared = prepare_prediction_frame(frame)

    rows: list[dict[str, object]] = []

    for key, model in models.items():

        if key not in MODEL_LABELS:
            continue

        prediction = int(
            model.predict(prepared)[0]
        )

        probability = float(
            model.predict_proba(
                prepared
            )[0, 1]
        )

        probability = max(
            0.0,
            min(
                1.0,
                probability,
            ),
        )

        rows.append(
            {
                "model_key": key,
                "Model": MODEL_LABELS[key],
                "Prediction": (
                    "Successful"
                    if prediction == 1
                    else "Failed"
                ),
                "Success probability": probability,
                "Failure probability": 1.0 - probability,
            }
        )

    return pd.DataFrame(rows)


# ============================================================
# BATCH PREDICTION
# ============================================================

def batch_predictions(
    models: dict[str, object],
    frame: pd.DataFrame,
) -> pd.DataFrame:
    """
    Generate predictions from every available model
    for multiple migration records.
    """

    if not models:
        raise ValueError(
            "No trained models are available. "
            "Run `python -m src.train` first."
        )

    prepared = prepare_prediction_frame(frame)

    output = frame.copy()

    for key, model in models.items():

        if key not in MODEL_LABELS:
            continue

        predictions = (
            model.predict(prepared)
            .astype(int)
        )

        probabilities = (
            model.predict_proba(
                prepared
            )[:, 1]
        )

        probabilities = probabilities.clip(
            0.0,
            1.0,
        )

        prefix = (
            MODEL_LABELS[key]
            .replace(" ", "_")
        )

        output[
            f"{prefix}_Prediction"
        ] = pd.Series(
            predictions,
            index=output.index,
        ).map(
            {
                1: "Successful",
                0: "Failed",
            }
        )

        output[
            f"{prefix}_Success_Probability"
        ] = probabilities.round(4)

        output[
            f"{prefix}_Failure_Probability"
        ] = (
            1.0 - probabilities
        ).round(4)

    return output


