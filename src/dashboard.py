def success_summary(
    data: pd.DataFrame,
) -> dict[str, float | int]:
    """Return basic migration success statistics."""

    total = len(data)

    successful = int(
        (data[TARGET_COLUMN] == 1).sum()
    )

    failed = int(
        (data[TARGET_COLUMN] == 0).sum()
    )

    success_rate = (
        successful / total
        if total
        else 0.0
    )

    return {
        "total": total,
        "successful": successful,
        "failed": failed,
        "success_rate": success_rate,
    }