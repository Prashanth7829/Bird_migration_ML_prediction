@st.cache_data(show_spinner=False)
def load_metrics() -> pd.DataFrame:
    """Load model comparison metrics generated by training."""

    path = MODELS_DIR / "model_metrics.csv"

    if not path.exists():
        return pd.DataFrame()

    metrics = pd.read_csv(path)

    required_columns = {
        "model_key",
        "model",
        "accuracy",
        "precision",
        "recall",
        "f1_score",
        "roc_auc",
    }

    missing = required_columns.difference(metrics.columns)

    if missing:
        raise ValueError(
            "model_metrics.csv is missing required columns: "
            + ", ".join(sorted(missing))
        )

    return metrics


def get_champion_key(
    metrics: pd.DataFrame | None = None,
) -> str | None:
    """
    Return the actual best model based on ROC-AUC and F1-score.

    Training already determines the champion, but this helper
    provides a safe dashboard-level fallback.
    """

    if metrics is None:
        metrics = load_metrics()

    if metrics.empty:
        return None

    if "roc_auc" in metrics.columns:
        sort_columns = ["roc_auc"]

        if "f1_score" in metrics.columns:
            sort_columns.append("f1_score")

        ranked = metrics.sort_values(
            sort_columns,
            ascending=False,
        )

        return str(ranked.iloc[0]["model_key"])

    return str(metrics.iloc[0]["model_key"])


def get_champion_name(
    metrics: pd.DataFrame | None = None,
) -> str:
    """Return the display name of the best model."""

    champion_key = get_champion_key(metrics)

    if champion_key is None:
        return "Not available"

    return MODEL_LABELS.get(
        champion_key,
        champion_key,
    )


