@st.cache_resource(show_spinner="Loading trained models...")
def load_models() -> dict[str, object]:
    """
    Load all available trained model pipelines.

    Each saved object should contain the complete preprocessing
    pipeline + classifier.
    """

    models: dict[str, object] = {}

    for key in MODEL_LABELS:

        path = model_path(key)

        if not path.exists():
            continue

        try:
            models[key] = joblib.load(path)

        except Exception as error:
            st.warning(
                f"Could not load {MODEL_LABELS[key]}: {error}"
            )

    return models


def available_model_keys() -> list[str]:
    """Return all trained model keys currently available."""

    return [
        key
        for key in MODEL_LABELS
        if model_path(key).exists()
    ]


def models_ready() -> bool:
    """
    Return True when all six required models are available.
    """

    return all(
        model_path(key).exists()
        for key in MODEL_LABELS
    )


def any_model_ready() -> bool:
    """Return True when at least one trained model exists."""

    return any(
        model_path(key).exists()
        for key in MODEL_LABELS
    )


